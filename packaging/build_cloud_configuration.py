"""Inject the project's Google Desktop registration without user-side setup.

The ignored generated module is included in PyInstaller's Python archive.
Never print its value or include personal access/refresh tokens in this module.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIXTURE_SECRET = "aurora-ci-fixture-not-a-real-google-client-secret"


def build_configuration(output: Path, *, client_id: str, secret: str, event: str) -> None:
    output = Path(output)
    # Never leave an older registration in place after a failed preparation.
    output.unlink(missing_ok=True)
    fixture = event == "pull_request"
    if fixture:
        secret = FIXTURE_SECRET
    if (not isinstance(client_id, str) or not client_id.endswith(".apps.googleusercontent.com")
            or len(client_id) > 256 or any(char.isspace() for char in client_id)
            or not isinstance(secret, str) or not 0 < len(secret) <= 256
            or any(not 33 <= ord(char) <= 126 for char in secret)):
        raise ValueError(
            "Configure o repository secret AURORA_GOOGLE_DESKTOP_CLIENT_SECRET "
            "antes de gerar um instalador para distribuição.")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        "# Generated by CI; do not commit. Desktop registration, not account credentials.\n"
        f"GOOGLE_CLIENT_ID = {client_id!r}\n"
        f"GOOGLE_CLIENT_SECRET = {secret!r}\n"
        f"IS_TEST_CONFIGURATION = {fixture!r}\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ci-event', choices=('push', 'workflow_dispatch', 'pull_request'), required=True)
    args = parser.parse_args()
    try:
        config = json.loads((ROOT / 'assets/cloud-oauth-clients.json').read_text(encoding='utf-8'))
        build_configuration(
            ROOT / 'app/_cloud_oauth.py', client_id=config.get('google', ''),
            secret=os.environ.get('AURORA_GOOGLE_DESKTOP_CLIENT_SECRET', ''), event=args.ci_event)
    except (ValueError, OSError) as exc:
        # Validation failures never include the supplied value.
        print(str(exc))
        return 1
    print('Google Desktop: configuração de teste preparada.' if args.ci_event == 'pull_request'
          else 'Google Desktop: configuração de distribuição preparada.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
